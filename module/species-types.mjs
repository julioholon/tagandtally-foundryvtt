import { TAGANDTALLY, SYSTEM_ID } from "./config.mjs";
import { SparkGenerator, generate } from "./sparks/engine.mjs";
import { sparkTables } from "./sparks/tables.mjs";

/**
 * Species and type builders (SRD guides "Species Creation" / "Type Creation").
 *
 * A species or type is an umbrella tag item whose `system.build` holds the SRD
 * sheet: the sentence, languages, magic access and base MAI, one weakness and
 * two or more abilities (each ability beyond two adds a flaw). Items live in the
 * world Items directory ("Species & Types" folder) as the library; dropping one
 * on a character replaces that sentence slot and grants the abilities as trait
 * tags, the weakness and extra flaws as hindering flaw tags, and sets the base
 * MAI to the higher of species and type.
 */

export const BUILDER_KINDS = ["species", "type"];

/** Sentence fields per kind, each with the Sparks table that rolls it. */
export const BUILD_FIELDS = {
  species: [
    { key: "aged", table: "character-species-aged" },
    { key: "descriptor", table: "character-species-descriptor" },
    { key: "cultural", table: "character-species-cultural-trait" },
    { key: "feature", table: "character-species-feature" }
  ],
  type: [
    { key: "descriptor", table: "descriptor" },
    { key: "noun", table: "type-[type-option]" },
    { key: "specializes", table: "does-something" }
  ]
};

/** Tables that inspire the weakness and abilities (humanoid creature tables). */
const WEAKNESS_TABLE = "creature-weakness-humanoid";
const ABILITY_TABLE = "creature-special-ability-humanoid";
const MIN_ABILITIES = 2;

const LIBRARY_FOLDER = "Species & Types";
const MAGICAL_RE = /\b(mag|arcan|wizard|sorcer|witch|warlock|druid|cleric|priest|mystic|shaman|spell|rune|aether|elemental)/i;

const plain = (s) => String(s ?? "").replace(/<[^>]+>/g, "").replace(/\*\*/g, "").replace(/[\[\]]/g, "").trim();

export function isBuilderTag(item) {
  return item?.type === "tag" && BUILDER_KINDS.includes(item.system.tagType) && item.system.isUmbrella;
}

/** Roll one Sparks table through the engine (theme-aware). */
async function rollField(table, { theme } = {}) {
  await sparkTables.load();
  const engine = new SparkGenerator({ theme: theme ?? game.settings.get(SYSTEM_ID, "sparkTheme") });
  const text = plain(await engine.render(`{${table}}`));
  return text.startsWith("[missing") ? "" : text;
}

/** How many flaws the ability count calls for (one per ability beyond two). */
export function flawsNeeded(build) {
  return Math.max(0, (build?.abilities?.length ?? 0) - MIN_ABILITIES);
}

/**
 * Build data for a species or type from a Sparks generation result (the
 * generator's values keyed by table), filling weakness and two abilities too.
 */
export async function buildFromGeneration(kind, r, { theme } = {}) {
  const v = r?.values ?? {};
  const build = { kind };
  for (const f of BUILD_FIELDS[kind]) {
    const raw = f.table.includes("[") ? Object.entries(v).find(([k]) => /^type(-|$)/.test(k) && k !== "type-option")?.[1] : v[f.table];
    build[f.key] = plain(raw ?? "") || await rollField(f.table, { theme });
  }
  build.weakness = await rollField(WEAKNESS_TABLE, { theme });
  const abilities = [];
  while (abilities.length < MIN_ABILITIES) {
    const text = await rollField(ABILITY_TABLE, { theme });
    if (!text) break;
    if (abilities.some((a) => a.name === text)) continue;
    abilities.push({ name: text, text: "", flaw: "" });
  }
  build.abilities = abilities;
  const magical = MAGICAL_RE.test(`${build.descriptor} ${build.noun} ${build.specializes} ${build.feature}`);
  build.magic = magical ? "use" : "none";
  build.baseMai = magical ? TAGANDTALLY.builder.magicalBaseMai : 0;
  return build;
}

/** Item data for a species or type generated by Sparks. */
export async function builderItemData(kind, r, { theme } = {}) {
  const build = await buildFromGeneration(kind, r, { theme });
  const name = kind === "species" ? `${build.descriptor} ${game.i18n.localize("TAGANDTALLY.Build.People")}` : build.noun;
  return {
    name: plain(name) || game.i18n.localize(TAGANDTALLY.tagTypes[kind]),
    type: "tag",
    img: TAGANDTALLY.builder.icons[kind],
    system: { tagType: kind, category: "umbrella", magical: build.magic !== "none", source: kind, build, description: r?.html ? `<p>${r.html}</p>` : "" }
  };
}

/** Regenerate the whole build of an existing species/type item (keeps edits to nothing). */
export async function regenerateBuild(item) {
  const kind = item.system.tagType;
  const r = await generate(kind, { theme: game.settings.get(SYSTEM_ID, "sparkTheme") });
  const data = await builderItemData(kind, r);
  return item.update({ name: data.name, "system.build": data.system.build, "system.magical": data.system.magical, "system.description": data.system.description });
}

/** A flaw from the SRD tarot flaws (one per card and orientation), avoiding ones already used. */
export async function drawFlaw(build) {
  const { TarotApp } = await import("./tarot.mjs");
  return TarotApp.drawFlaw([build?.weakness, ...(build?.abilities ?? []).map((a) => a.flaw)].filter(Boolean));
}

/** Reroll one sentence field, the weakness, one ability, or the flaw paying for an ability. */
export async function rerollBuildField(item, key, index) {
  const kind = item.system.tagType;
  if (key === "weakness") return item.update({ "system.build.weakness": await rollField(WEAKNESS_TABLE) });
  if (key === "flaw") {
    const abilities = foundry.utils.deepClone(item.system.build.abilities);
    if (!abilities[index]) return item;
    abilities[index].flaw = await drawFlaw(item.system.build);
    return item.update({ "system.build.abilities": abilities });
  }
  if (key === "ability") {
    const abilities = foundry.utils.deepClone(item.system.build.abilities);
    if (!abilities[index]) return item;
    abilities[index].name = await rollField(ABILITY_TABLE);
    return item.update({ "system.build.abilities": abilities });
  }
  const field = BUILD_FIELDS[kind]?.find((f) => f.key === key);
  if (!field) return item;
  return item.update({ [`system.build.${key}`]: await rollField(field.table) });
}

/** The world Items folder that holds the library. */
export async function libraryFolder() {
  let folder = game.folders.find((f) => f.type === "Item" && f.name === LIBRARY_FOLDER);
  folder ??= await Folder.create({ name: LIBRARY_FOLDER, type: "Item" });
  return folder;
}

/** Species and types in the world library (world items only). */
export function libraryItems(kind) {
  return game.items.filter((i) => isBuilderTag(i) && (!kind || i.system.tagType === kind));
}

/**
 * Create a species or type in the library from the Sparks generator.
 * @returns {Item}
 */
export async function createBuilderItem(kind, { render = true } = {}) {
  const r = await generate(kind, { theme: game.settings.get(SYSTEM_ID, "sparkTheme") });
  const data = await builderItemData(kind, r);
  data.folder = (await libraryFolder()).id;
  const item = await Item.create(data);
  if (render) item.sheet.render({ force: true });
  return item;
}

/**
 * Apply a species or type to a character: replace the sentence slot and its
 * umbrella tag, grant abilities (trait tags), the weakness and extra flaws
 * (hindering flaw tags) and set base MAI = max(species, type).
 * @param {Actor} actor
 * @param {Item} item  a species/type item (world or another actor's)
 */
export async function applyBuilderItem(actor, item) {
  if (actor.type !== "character" || !isBuilderTag(item)) return null;
  const kind = item.system.tagType;
  const build = foundry.utils.deepClone(item.system.build);
  const source = item.toObject();
  delete source._id;
  delete source.folder;
  source.system.umbrella = "";
  // Out with the old slot: the umbrella tag and everything it granted.
  const old = actor.items.filter((i) => i.type === "tag" && i.system.tagType === kind && i.system.isUmbrella);
  const granted = actor.items.filter((i) => i.type === "tag" && old.some((o) => o.id === i.system.umbrella));
  const ids = [...old, ...granted].map((i) => i.id);
  if (ids.length) await actor.deleteEmbeddedDocuments("Item", ids);
  const [umbrella] = await actor.createEmbeddedDocuments("Item", [source]);
  const subs = [];
  const L = (k, d) => game.i18n.format(`TAGANDTALLY.Build.${k}`, d);
  for (const a of build.abilities ?? []) {
    if (!a.name) continue;
    subs.push({ name: a.name, type: "tag", img: TAGANDTALLY.builder.icons.ability, system: { tagType: "trait", category: "static", umbrella: umbrella.id, magical: build.magic === "use" && MAGICAL_RE.test(a.name), description: a.text ? `<p>${foundry.utils.escapeHTML(a.text)}</p>` : `<p>${L("GrantedBy", { name: umbrella.name })}</p>` } });
    if (a.flaw) subs.push({ name: a.flaw, type: "tag", img: TAGANDTALLY.builder.icons.flaw, system: { tagType: "flaw", category: "static", hinders: true, umbrella: umbrella.id, description: `<p>${L("FlawFor", { ability: a.name, name: umbrella.name })}</p>` } });
  }
  if (build.weakness) subs.push({ name: build.weakness, type: "tag", img: TAGANDTALLY.builder.icons.flaw, system: { tagType: "flaw", category: "static", hinders: true, umbrella: umbrella.id, description: `<p>${L("WeaknessOf", { name: umbrella.name })}</p>` } });
  if (subs.length) await actor.createEmbeddedDocuments("Item", subs);
  // Sentence slot and base MAI (the higher of species and type, never the sum).
  const update = { [`system.sentence.${kind}`]: umbrella.name };
  const bases = actor.items.filter((i) => isBuilderTag(i) && i.system.build?.hasContent).map((i) => Number(i.system.build.baseMai) || 0);
  if (bases.length) update["system.mai.base"] = Math.max(...bases);
  await actor.update(update, { ttSentenceSync: false });
  ui.notifications.info(L("Applied", { name: umbrella.name, actor: actor.name, count: subs.length }));
  return umbrella;
}

/** Pick a character and apply the item to it. */
export async function applyBuilderItemDialog(item) {
  const chars = game.actors.filter((a) => a.type === "character" && a.isOwner);
  if (!chars.length) return ui.notifications.warn(game.i18n.localize("TAGANDTALLY.Build.NoCharacters"));
  const options = chars.map((a) => `<option value="${a.id}">${foundry.utils.escapeHTML(a.name)}</option>`).join("");
  const id = await foundry.applications.api.DialogV2.prompt({
    window: { title: game.i18n.localize("TAGANDTALLY.Build.Apply") },
    content: `<p>${game.i18n.format("TAGANDTALLY.Build.ApplyHint", { name: foundry.utils.escapeHTML(item.name) })}</p><div class="form-group"><select name="actor">${options}</select></div>`,
    ok: { label: game.i18n.localize("TAGANDTALLY.Build.Apply"), callback: (event, button) => button.form.elements.actor.value },
    rejectClose: false
  });
  if (!id) return null;
  return applyBuilderItem(game.actors.get(id), item);
}

/** Sentence text for a build (brackets mark the tags). */
export function buildSentence(build, { word }) {
  if (!build) return "";
  const t = (s) => (s ? `[${s}]` : "");
  if (build.kind === "type" || !("aged" in build)) {
    const parent = build.parent ? ` ${word("TypeKindOf", "a kind of")} ${t(build.parent)}.` : "";
    return `${word("TypeIsA", "This type is a")} ${t(build.descriptor)} ${t(build.noun)} ${word("Who", "who")} ${t(build.specializes)}.${parent}`;
  }
  return `${word("SpeciesIsA", "This species is a")} ${t(build.aged)} ${t(build.descriptor)} ${word("PeopleWho", "people who")} ${t(build.cultural)} ${word("And", "and")} ${t(build.feature)}.`;
}
